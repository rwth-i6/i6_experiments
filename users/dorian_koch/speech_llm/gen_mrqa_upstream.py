"""Generate speech_llm/mrqa_upstream.py from the pinned moshi-rag sources (no hand transcription).

A script, not a module: ``python3 gen_mrqa_upstream.py <dir> mrqa_upstream.py``, where ``<dir>`` holds the pinned
``moshi/moshi/evaluate`` files flattened: ``evaluate_utils.py`` (``utils.py``), ``evaluate_score.py``,
``evaluate_judge_{base,simple_qa,open_audio_bench,math_qa}.py`` (``judge/*.py``).

Every upstream function/prompt is copied by AST source segment, so the port is byte-identical to the
pinned commit except for the documented, mechanical edits applied here (method -> function rename,
eval -> ast.literal_eval). The guard check_mrqa_faithful.py re-derives the same thing from a clone.
"""

import ast
import sys
import textwrap
from pathlib import Path

